#ifndef WHATEVER_HPP
#define WHATEVER_HPP

// このヘッダーには 3 つのテンプレート関数を “定義” まで書く。
// テンプレートはリンク時点で型が決まるため、実装を .cpp に分けると
// リンカがシンボルを見つけられず未定義参照になる。

/* ************************************************************************** */
/*                                swap 関数                                   */
/* ************************************************************************** */
/**
 * 2 つの変数の値を入れ替える。
 * @param a 変数 1（参照渡し）
 * @param b 変数 2（参照渡し）
 */
template <typename T> void swap(T &a, T &b)
{
	// 一時的に a の値を保存し、a に b を代入、b に保存しておいた値を戻す
	T tmp = a;
	a = b;
	b = tmp;
}

/* ************************************************************************** */
/*                                 min 関数                                   */
/* ************************************************************************** */
/**
 * 2 つの値を比較して小さい方を返す。
 * 同値の場合は **第 2 引数** を返すという課題仕様に合わせている。
 */
template <typename T> T const &min(T const &a, T const &b)
{
	// (a < b) が true なら a、false なら b
	return (a < b) ? a : b;
}

/* ************************************************************************** */
/*                                 max 関数                                   */
/* ************************************************************************** */
/**
 * 2 つの値を比較して大きい方を返す。
 * 同値の場合は **第 2 引数** を返すという課題仕様に合わせている。
 */
template <typename T> T const &max(T const &a, T const &b)
{
	// (a > b) が true なら a、false なら b
	return (a > b) ? a : b;
}

#endif /* WHATEVER_HPP */
